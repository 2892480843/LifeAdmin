import { existsSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const DEFAULT_ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)))

const SHARDS = [
  { key: 'featured', exportName: 'featuredPois', file: 'featured.ts' },
  { key: 'north', exportName: 'northPois', file: 'north.ts' },
  { key: 'east', exportName: 'eastPois', file: 'east.ts' },
  { key: 'south', exportName: 'southPois', file: 'south.ts' },
  { key: 'central', exportName: 'centralPois', file: 'central.ts' },
  { key: 'southwest', exportName: 'southwestPois', file: 'southwest.ts' },
  { key: 'northwest', exportName: 'northwestPois', file: 'northwest.ts' },
  { key: 'northeast', exportName: 'northeastPois', file: 'northeast.ts' },
]

const FEATURED_CITY_IDS = new Set(['beijing', 'shanghai', 'hangzhou', 'chengdu', 'xian', 'sanya'])

const REGION_BY_PROVINCE_PREFIX = {
  '11': 'north',
  '12': 'north',
  '13': 'north',
  '14': 'north',
  '15': 'north',
  '21': 'northeast',
  '22': 'northeast',
  '23': 'northeast',
  '31': 'east',
  '32': 'east',
  '33': 'east',
  '34': 'east',
  '35': 'east',
  '36': 'east',
  '37': 'east',
  '41': 'central',
  '42': 'central',
  '43': 'central',
  '44': 'south',
  '45': 'south',
  '46': 'south',
  '50': 'southwest',
  '51': 'southwest',
  '52': 'southwest',
  '53': 'southwest',
  '54': 'southwest',
  '61': 'northwest',
  '62': 'northwest',
  '63': 'northwest',
  '64': 'northwest',
  '65': 'northwest',
}

export async function buildGeneratedPois(options = {}) {
  const root = options.root || DEFAULT_ROOT
  const quiet = options.quiet === true
  const citySourcePath = resolve(root, 'src/data/china-prefecture-cities.json')
  const dataPath = resolve(root, 'data/generated-pois.json')
  const outDir = resolve(root, 'src/mock/generatedPois')
  const cityData = readJsonIfExists(citySourcePath, { cities: [] })
  const pois = readJsonIfExists(dataPath, [])
  const cities = Array.isArray(cityData?.cities) ? cityData.cities : []
  const cityById = new Map(cities.map((city) => [city.id, city]))
  const buckets = Object.fromEntries(SHARDS.map((shard) => [shard.key, []]))
  const poiShardIndex = {}

  for (const poi of Array.isArray(pois) ? pois : []) {
    const shard = shardForPoi(poi, cityById)
    buckets[shard].push(poi)
    if (poi?.id) poiShardIndex[String(poi.id)] = shard
  }

  if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true })

  for (const shard of SHARDS) {
    const filePath = resolve(outDir, shard.file)
    const content = [
      "import type { Poi } from '../../types'",
      '',
      '// Generated by scripts/build-generated-pois.mjs. Do not edit manually.',
      `export const ${shard.exportName}: Poi[] = ${JSON.stringify(sortPois(buckets[shard.key]), null, 2)}`,
      '',
    ].join('\n')
    writeTextFile(filePath, content)
  }

  writeTextFile(resolve(outDir, 'index.ts'), buildIndexContent())
  writeTextFile(resolve(outDir, 'poiShardIndex.ts'), buildPoiShardIndexContent(poiShardIndex))

  if (!quiet) {
    console.log('[build-generated-pois] wrote shards:')
    for (const shard of SHARDS) console.log(`  ${shard.key}: ${buckets[shard.key].length}`)
  }

  return buckets
}

function buildPoiShardIndexContent(poiShardIndex) {
  const sorted = Object.fromEntries(
    Object.entries(poiShardIndex).sort(([left], [right]) => left.localeCompare(right)),
  )
  return [
    "import type { PoiShardKey } from '../poiLoader'",
    '',
    '// Generated by scripts/build-generated-pois.mjs. Do not edit manually.',
    `export const poiShardIndex: Record<string, PoiShardKey> = ${JSON.stringify(sorted, null, 2)}`,
    '',
  ].join('\n')
}

function buildIndexContent() {
  return [
    "import type { Poi } from '../../types'",
    "import { featuredPois } from './featured'",
    "import { northPois } from './north'",
    "import { eastPois } from './east'",
    "import { southPois } from './south'",
    "import { centralPois } from './central'",
    "import { southwestPois } from './southwest'",
    "import { northwestPois } from './northwest'",
    "import { northeastPois } from './northeast'",
    '',
    '// Generated by scripts/build-generated-pois.mjs. Do not edit manually.',
    'export const generatedPois: Poi[] = [',
    '  ...featuredPois,',
    '  ...northPois,',
    '  ...eastPois,',
    '  ...southPois,',
    '  ...centralPois,',
    '  ...southwestPois,',
    '  ...northwestPois,',
    '  ...northeastPois,',
    ']',
    '',
    'export { featuredPois } from \'./featured\'',
    'export { northPois } from \'./north\'',
    'export { eastPois } from \'./east\'',
    'export { southPois } from \'./south\'',
    'export { centralPois } from \'./central\'',
    'export { southwestPois } from \'./southwest\'',
    'export { northwestPois } from \'./northwest\'',
    'export { northeastPois } from \'./northeast\'',
    '',
  ].join('\n')
}

function shardForPoi(poi, cityById) {
  if (FEATURED_CITY_IDS.has(poi.cityId)) return 'featured'
  const city = cityById.get(poi.cityId)
  const prefix = String(city?.adcode || '').slice(0, 2)
  return REGION_BY_PROVINCE_PREFIX[prefix] || 'east'
}

function sortPois(pois) {
  return [...pois].sort((left, right) => {
    const city = String(left.cityId || '').localeCompare(String(right.cityId || ''))
    if (city) return city
    return String(left.name || '').localeCompare(String(right.name || ''))
  })
}

function readJsonIfExists(path, fallback) {
  if (!existsSync(path)) return fallback
  return JSON.parse(readFileSync(path, 'utf8'))
}

function writeTextFile(path, text) {
  const tempPath = `${path}.${process.pid}.${Date.now()}.tmp`
  writeFileSync(tempPath, text, 'utf8')
  for (let attempt = 1; attempt <= 8; attempt += 1) {
    try {
      renameSync(tempPath, path)
      return
    } catch (error) {
      if (attempt === 8) {
        try {
          rmSync(tempPath, { force: true })
        } catch {
          // best effort cleanup
        }
        throw error
      }
      sleepSync(80 * attempt)
    }
  }
}

function sleepSync(ms) {
  const buffer = new SharedArrayBuffer(4)
  const view = new Int32Array(buffer)
  Atomics.wait(view, 0, 0, ms)
}

const isDirectRun = process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])

if (isDirectRun) {
  buildGeneratedPois().catch((error) => {
    console.error('[build-generated-pois] failed:', error instanceof Error ? error.message : String(error))
    process.exit(1)
  })
}
